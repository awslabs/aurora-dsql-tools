//! Detection AND collapse of the pg_dump "SERIAL idiom".
//!
//! A real PostgreSQL `pg_dump` expands a `SERIAL`/`bigserial` column into four
//! separate statements:
//!
//! ```sql
//! CREATE TABLE public.t (id integer NOT NULL, x text);
//! CREATE SEQUENCE public.t_id_seq START WITH 1 INCREMENT BY 1 NO MINVALUE NO MAXVALUE CACHE 1;
//! ALTER SEQUENCE public.t_id_seq OWNED BY public.t.id;
//! ALTER TABLE ONLY public.t ALTER COLUMN id SET DEFAULT nextval('public.t_id_seq'::regclass);
//! ```
//!
//! ## Why collapse?
//! DSQL accepts `CREATE SEQUENCE ... CACHE 1` and `ALTER SEQUENCE ... OWNED BY`
//! at the executor level, but `ALTER TABLE ... ALTER COLUMN ... SET DEFAULT
//! nextval(...)` is rejected outright. The cleaner DSQL-idiomatic shape is a
//! single inline
//! `BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1)` column, which is what
//! this module collapses the four-statement quartet into.
//!
//! This module exposes three entry points used by the lint engine:
//! - [`detect_serial_idioms`] (pure, AST-only) — finds idioms across a parsed
//!   statement list and returns structured info pointing at each piece.
//! - [`check_serial_idioms`] (lint pass) — surfaces a single
//!   `SerialSequenceIdiom` diagnostic per detected idiom, without touching input.
//! - [`fix_serial_idioms`] (fix pass) — rewrites the CREATE TABLE column to an
//!   inline `BIGINT GENERATED BY DEFAULT AS IDENTITY (CACHE 1)` and removes the
//!   redundant CREATE SEQUENCE / SET DEFAULT statements, along with the
//!   sequence's `ALTER SEQUENCE ... OWNED BY` and `OWNER TO` statements.
//!
//! ## Index space
//! Detection operates on the successfully-parsed statements (CREATE TABLE,
//! CREATE SEQUENCE, ALTER TABLE), and the fix pass finds the sequence's
//! ALTER SEQUENCE statements among them too. Every index in [`SerialIdiom`]
//! (`create_table_index`, `redundant_indices`) is an index into the `stmts`
//! slice handed to [`detect_serial_idioms`]; the lint and fix passes here
//! translate those back to indices into the original `parts` list via a
//! `parsed_to_part` mapping built by [`parse_parts`].

use sqlparser::ast::{
    AlterColumnOperation, AlterSequence, AlterSequenceOperation, AlterTableOperation, ColumnOption,
    DataType, Expr, FunctionArg, FunctionArgExpr, FunctionArguments, Statement, Value,
    ValueWithSpan,
};
use sqlparser::dialect::PostgreSqlDialect;
use sqlparser::parser::Parser;

use super::errors::identity_by_default_cache_1;
